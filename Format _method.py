# FORMAT METHOD (STRINGS)
# Formats the values inside the string into a desired output.
# template.format(p1,p2...)
# Syntax:
# "{} is a good {}".format("harry", "boy") #1.
# "{} is a good {o}".format("harry", "boy") #2.
# # output for 1:
# # harry is a good boy
# # output for 2:
# # boy is a good harry




print("{} is a nice person {}".format("Prashant","ok"))
print("{1} is a nice person {0}".format("Prashant","ok")) # you can use number as index

